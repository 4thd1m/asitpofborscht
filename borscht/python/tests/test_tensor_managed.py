"""Tests for borscht.tensor_managed, extracted from its doctests.

Run from `borscht/`:

    pytest python/tests/test_tensor_managed.py
"""

import pytest

from borscht.tensor_managed import full, mm


# + ============================================================================================================
#                                              0. Naming Tensors
# + ============================================================================================================


def test_float_addition_is_not_associative():
    assert (0.1 + 0.2) + 0.3 == 0.6000000000000001
    assert 0.1 + (0.2 + 0.3) == 0.6


def test_float_multiplication_does_not_distribute():
    assert 0.9 * (0.2 + 0.3) == 0.45
    assert 0.9 * 0.2 + 0.9 * 0.3 == 0.45000000000000007


# + ============================================================================================================
#                                              1. Constructing Tensors
# + ============================================================================================================


def test_full():
    A = full((2, 3), 3.141592)
    assert A.shape == (2, 3)
    assert repr(A) == (
        "tensor([[3.1416, 3.1416, 3.1416],\n"
        "        [3.1416, 3.1416, 3.1416]])"
    )


# + ============================================================================================================
#                                              2. Reading Tensors
# + ============================================================================================================


@pytest.mark.parametrize(
    "shape, expected",
    [
        pytest.param((), "tensor(3.1416)", id="scalar"),
        pytest.param((3,), "tensor([3.1416, 3.1416, 3.1416])", id="vector"),
        pytest.param(
            (2, 3),
            "tensor([[3.1416, 3.1416, 3.1416],\n"
            "        [3.1416, 3.1416, 3.1416]])",
            id="matrix",
        ),
        pytest.param(
            (2, 2, 3),
            "tensor([[[3.1416, 3.1416, 3.1416],\n"
            "         [3.1416, 3.1416, 3.1416]],\n"
            "\n"
            "        [[3.1416, 3.1416, 3.1416],\n"
            "         [3.1416, 3.1416, 3.1416]]])",
            id="rank3",
        ),
        pytest.param(
            (3, 2, 2, 3),
            "tensor([[[[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]],\n"
            "\n"
            "         [[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]]],\n"
            "\n"
            "\n"
            "        [[[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]],\n"
            "\n"
            "         [[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]]],\n"
            "\n"
            "\n"
            "        [[[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]],\n"
            "\n"
            "         [[3.1416, 3.1416, 3.1416],\n"
            "          [3.1416, 3.1416, 3.1416]]]])",
            id="rank4",
        ),
    ],
)
def test_repr(shape, expected):
    assert repr(full(shape, 3.141592)) == expected


# + ============================================================================================================
#                                              3. Updating Tensors
# + ============================================================================================================


def test_mm():
    A = full((2, 3), 3.141592)
    B = full((3, 2), 3.141592)
    assert repr(mm(A, B)) == (
        "tensor([[29.6088, 29.6088],\n"
        "        [29.6088, 29.6088]])"
    )


def test_mm_shape_mismatch():
    A = full((2, 3), 3.141592)
    with pytest.raises(RuntimeError, match=r"A and B shapes cannot be multiplied \(2x3 and 2x3\)"):
        mm(A, A)
